import { test, expect } from '@playwright/test';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../../', import.meta.url));

test('upload, masked results, downloads, history and firmware comparison', async ({page}) => {
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Scan a firmware file'})).toBeVisible();
  await page.getByLabel('Device label',{exact:true}).fill('Browser test router');
  await page.getByLabel('Version label',{exact:true}).fill('1.0');
  await page.getByLabel('Firmware or configuration file').setInputFiles(path.join(root,'samples/firmware_v1.zip'));
  await page.getByRole('button',{name:'Run analysis'}).click();
  await expect(page.getByRole('heading',{name:'Results: Browser test router / 1.0'})).toBeVisible({timeout:30000});
  await expect(page.getByRole('cell',{name:'Hardcoded password',exact:false}).first()).toBeVisible();
  await expect(page.locator('main')).not.toContainText('dummy_old_value');
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('link',{name:'Download PDF',exact:true}).click();
  const download=await downloadPromise;expect(download.suggestedFilename()).toMatch(/firmguard-scan-\d+\.pdf/);
  await page.getByRole('tab',{name:'Software',exact:true}).click();
  await expect(page.getByRole('cell',{name:'OpenSSL',exact:true})).toBeVisible();
  await page.getByRole('tab',{name:'ELF files',exact:true}).click();
  await expect(page.getByRole('cell',{name:'disabled',exact:true}).first()).toBeVisible();
  await page.getByRole('button',{name:'Scan',exact:true}).click();
  await page.getByLabel('Version label',{exact:true}).fill('2.0');
  await page.getByLabel('Firmware or configuration file').setInputFiles(path.join(root,'samples/firmware_v2.tar.gz'));
  await page.getByRole('button',{name:'Run analysis'}).click();
  await expect(page.getByRole('heading',{name:'Results: Browser test router / 2.0'})).toBeVisible({timeout:30000});
  await page.getByRole('button',{name:'History',exact:true}).click();
  await expect(page.getByRole('cell',{name:'Browser test router',exact:false})).toHaveCount(2);
  await page.getByRole('button',{name:'Compare',exact:true}).click();
  const selects=page.locator('form select');
  await expect(selects.first().locator('option')).toHaveCount(3);
  const baseline=await selects.first().locator('option').last().getAttribute('value');
  const candidate=await selects.last().locator('option').nth(1).getAttribute('value');
  await selects.first().selectOption(baseline);await selects.last().selectOption(candidate);
  await page.getByRole('button',{name:'Compare scans',exact:true}).click();
  await expect(page.getByRole('heading',{name:'1.0 → 2.0'})).toBeVisible();
  await expect(page.getByRole('cell',{name:'etc/new.conf',exact:true})).toBeVisible();
  await expect(page.getByRole('cell',{name:'etc/old.conf',exact:true})).toBeVisible();
  const comparisonDownload=page.waitForEvent('download');
  await page.getByRole('link',{name:'Download comparison PDF'}).click();
  expect((await comparisonDownload).suggestedFilename()).toContain('comparison');
  await page.screenshot({path:path.join(root,'docs/interface.png'),fullPage:true});
  expect(errors).toEqual([]);
});

test('small-screen layout and safe sample selection', async ({page}) => {
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await page.getByText('Try the supplied samples',{exact:true}).click();
  await page.getByRole('button',{name:'Safe configuration',exact:true}).click();
  await page.getByRole('button',{name:'Run analysis',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Results: Lab router / v1.0'})).toBeVisible({timeout:30000});
  await expect(page.locator('main')).toContainText('No findings match this filter');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Help',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Limits and interpretation'})).toBeVisible();
});
